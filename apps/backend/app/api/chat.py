"""
ORBIT — Gemini-Powered Streaming Chat API.
Phase 8: Backend Chat API with Gemini Streaming.

Implements:
  - POST /api/chat -> Streaming chatbot assistant using Google Gemini API.
"""
from __future__ import annotations

import asyncio
import logging
import os
from typing import AsyncGenerator, List, Literal

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

import google.generativeai as genai
from app.core.config import get_settings

logger = logging.getLogger("orbit.api.chat")

router = APIRouter(prefix="/api/chat", tags=["chat"])

# Primary model per specification, with graceful fallback if deprecated/quota-limited by Google API
PRIMARY_MODEL = "gemini-2.0-flash"
FALLBACK_MODELS = ["gemini-3.5-flash", "gemini-3.8-flash", "gemini-flash-latest"]


class ChatHistoryItem(BaseModel):
    role: Literal["user", "model", "assistant"] = Field(
        ..., description="Message author role: 'user' or 'model'"
    )
    content: str = Field(..., description="Message text content")


class ChatRequest(BaseModel):
    message: str = Field(..., description="Current user input text")
    history: List[ChatHistoryItem] = Field(
        default_factory=list, description="Prior conversation history"
    )


def _get_api_key() -> str:
    """
    Retrieves the GEMINI_API_KEY from settings or environment.
    """
    settings = get_settings()
    key = getattr(settings, "gemini_api_key", None) or os.getenv("GEMINI_API_KEY")
    if not key or not str(key).strip() or str(key).strip().startswith("your_"):
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="🛑 API KEY REQUIRED: I need a valid GEMINI_API_KEY to test the chat endpoint.",
        )
    return str(key).strip()


def _format_history_contents(
    history: List[ChatHistoryItem], current_message: str
) -> list[dict[str, list[str]]]:
    """
    Maps incoming chat history and current message into google-generativeai contents format.
    """
    contents: list[dict[str, list[str]]] = []
    for item in history:
        normalized_role = "model" if item.role in ("model", "assistant") else "user"
        contents.append({"role": normalized_role, "parts": [item.content]})

    contents.append({"role": "user", "parts": [current_message]})
    return contents


def _create_gemini_stream(
    contents: list[dict[str, list[str]]],
    api_key: str,
):
    """
    Initializes Gemini client and yields streaming response chunks using gemini-2.0-flash.
    Gracefully falls back to supported Gemini flash models if provider reports model deprecation.
    """
    genai.configure(api_key=api_key, transport="rest")

    # Try primary requested model first
    models_to_try = [PRIMARY_MODEL] + FALLBACK_MODELS
    last_error: Exception | None = None

    for model_name in models_to_try:
        try:
            model = genai.GenerativeModel(model_name)
            response = model.generate_content(contents, stream=True)
            return response
        except Exception as exc:
            last_error = exc
            logger.warning(
                "Gemini model '%s' failed (%s). Attempting fallback...", model_name, exc
            )

    if last_error:
        raise last_error


@router.post("")
@router.post("/")
def chat_with_gemini(body: ChatRequest) -> StreamingResponse:
    """
    POST /api/chat
    Streams real-time text tokens generated by Gemini using StreamingResponse.
    Accepts: { "message": "...", "history": [{ "role": "user|model", "content": "..." }] }
    """
    api_key = _get_api_key()
    contents = _format_history_contents(body.history, body.message)

    def stream_generator():
        try:
            response_stream = _create_gemini_stream(contents, api_key)
            for chunk in response_stream:
                try:
                    if chunk and hasattr(chunk, "text") and chunk.text:
                        yield chunk.text
                except (ValueError, AttributeError):
                    continue
        except Exception as exc:
            logger.exception("Error in Gemini chat stream: %s", exc)
            yield f"\n\n[Chat Error: {str(exc)}]"

    return StreamingResponse(
        stream_generator(),
        media_type="text/plain; charset=utf-8",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )
