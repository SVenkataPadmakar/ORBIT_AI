"""
ORBIT — Shared State Contract & LangGraph State Definition.
Defines @dataclass OrbitState, ProgressEvent, and typed audit models.

Non-negotiable Constitution:
- 7 agents only: problem_discovery, market_analysis, feasibility, prd_generator, design, developer, risk_analysis.
- Strictly linear pipeline.
- If feasibility.score < 80 -> pipeline stops with status 'stopped_low_feasibility'.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Annotated, Any, Literal
from uuid import uuid4

from pydantic import BaseModel, Field


# ─── PROGRESS EVENT CONTRACT (MANDATORY FOR ALL 7 AGENTS) ────────────────────

class ProgressEvent(BaseModel):
    """
    Mandatory SSE progress event contract emitted by all 7 agents:
    {
      "run_id": str, "agent": str, "agent_index": int,   # 1..7
      "status": "pending|running|done|failed",
      "percent": int,   # 0..100
      "message": str, "eta_seconds": int | null
    }
    """
    run_id: str
    agent: str
    agent_index: int = Field(..., ge=1, le=7)
    status: Literal["pending", "running", "done", "failed"]
    percent: int = Field(..., ge=0, le=100)
    message: str
    eta_seconds: int | None = None
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


# ─── AUDIT & ARTIFACT CONTRACTS ──────────────────────────────────────────────

class ToolCallRecord(BaseModel):
    """Immutable audit record for every typed tool invocation made by an agent."""
    call_id: str = Field(default_factory=lambda: str(uuid4()))
    agent: str
    tool_name: str
    input_payload: dict[str, Any] = Field(default_factory=dict)
    output_payload: dict[str, Any] = Field(default_factory=dict)
    execution_time_ms: float = 0.0
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    status: Literal["success", "failure"] = "success"


class ArtifactRecord(BaseModel):
    """Immutable artifact generated by an agent."""
    artifact_id: str = Field(default_factory=lambda: str(uuid4()))
    artifact_type: str
    name: str
    file_path: str = ""
    content: Any = None
    metadata: dict[str, Any] = Field(default_factory=dict)
    version: int = 1
    sha256: str = ""
    download_url: str = ""
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class IdeaSpec(BaseModel):
    """Initial founder concept input specification."""
    title: str = ""
    summary: str = ""
    target_users: list[str] = Field(default_factory=list)
    core_problem: str = ""
    constraints: list[str] = Field(default_factory=list)
    monetization: str = ""


# Legacy aliases for backward compatibility with telemetry and recovery loggers
class TelemetryEvent(BaseModel):
    run_id: str
    node: str
    agent: str
    ts: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    tokens_delta: int = 0
    step_delta: int = 1
    status: Literal["started", "running", "completed", "failed", "repaired"] = "running"
    details: dict[str, Any] = Field(default_factory=dict)


class CommitRecord(BaseModel):
    commit_hash: str
    message: str
    author: str
    files: list[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class FailureRecord(BaseModel):
    failure_id: str = Field(default_factory=lambda: str(uuid4()))
    node: str
    agent: str
    error_type: str
    message: str
    stack_trace: str | None = None
    context: dict[str, Any] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())
    resolved: bool = False


class RepairRecord(BaseModel):
    repair_id: str = Field(default_factory=lambda: str(uuid4()))
    target_failure_id: str
    agent: str = "RepairAgent"
    action_taken: str
    diff_applied: str | None = None
    files_touched: list[str] = Field(default_factory=list)
    success: bool = False
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


# ─── REDUCER FUNCTIONS FOR LANGGRAPH ─────────────────────────────────────────

def list_append_reducer(current: list[Any] | None, update: list[Any] | Any | None) -> list[Any]:
    """Appends item(s) to an existing list in state idempotently."""
    base = list(current or [])
    if update is None:
        return base
    if isinstance(update, list):
        return base + update
    return base + [update]


def dict_merge_reducer(current: dict[str, Any] | None, update: dict[str, Any] | None) -> dict[str, Any]:
    """Merges two dictionaries in state shallowly without mutating current."""
    base = dict(current or {})
    if update:
        base.update(update)
    return base


# ─── ORBIT STATE DEFINITION (CONSTITUTION: 7 AGENTS LINEAR) ──────────────────

@dataclass
class OrbitState:
    """
    Central Supervisor State for ORBIT LangGraph.
    Tracks execution across exactly 7 agents in a strictly linear pipeline:
      1. problem_discovery
      2. market_analysis
      3. feasibility (score < 80 stops pipeline with status 'stopped_low_feasibility')
      4. prd_generator
      5. design
      6. developer (sandbox, produces orbit.zip)
      7. risk_analysis
    """
    # Required core attributes
    run_id: str = field(default_factory=lambda: f"orbit-run-{uuid4().hex[:12]}")
    tenant_id: str = "tenant-default"
    user_id: str = "user-default"
    idea: Any = field(default_factory=IdeaSpec)

    # Deliverables & artifacts generated by the 7 agents
    problem_md: str | None = None
    market_md: str | None = None
    feasibility: dict[str, Any] = field(default_factory=dict)
    prd_md: str | None = None
    design: dict[str, Any] = field(default_factory=dict)  # architecture, schema_sql, openapi, wireframes
    workspace_uri: str | None = None
    zip_uri: str | None = None
    risk_md: str | None = None

    # Telemetry, progress and error collections with reducers
    progress: Annotated[dict[str, int], dict_merge_reducer] = field(default_factory=dict)  # agent -> percent (0..100)
    errors: Annotated[list[Any], list_append_reducer] = field(default_factory=list)
    status: Literal["pending", "running", "done", "failed", "stopped_low_feasibility", "stopped_feasibility"] = "pending"

    # Supervisor & legacy compatibility attributes
    current_agent: str = "problem_discovery"
    current_agent_index: int = 1
    current_node: str = "problem_discovery"
    feasibility_passed: bool = True
    deliverable_zip_path: str | None = None
    deliverable_sha256: str | None = None
    problem_discovery: dict[str, Any] | None = None
    market_analysis: dict[str, Any] | None = None
    prd: dict[str, Any] | None = None
    developer: dict[str, Any] | None = None
    risk_analysis: dict[str, Any] | None = None
    tool_calls: Annotated[list[ToolCallRecord], list_append_reducer] = field(default_factory=list)
    artifacts: Annotated[dict[str, ArtifactRecord], dict_merge_reducer] = field(default_factory=dict)
    progress_events: Annotated[list[ProgressEvent], list_append_reducer] = field(default_factory=list)
    budgets: Annotated[dict[str, Any], dict_merge_reducer] = field(default_factory=dict)
    terminal_status: str = "IN_PROGRESS"
    is_terminal: bool = False
    telemetry_events: Annotated[list[TelemetryEvent], list_append_reducer] = field(default_factory=list)
    commits: Annotated[list[CommitRecord], list_append_reducer] = field(default_factory=list)
    failures: Annotated[list[FailureRecord], list_append_reducer] = field(default_factory=list)
    repairs: Annotated[list[RepairRecord], list_append_reducer] = field(default_factory=list)


def create_initial_state(
    run_id: str | None = None,
    tenant_id: str = "tenant-default",
    user_id: str = "user-default",
    idea: dict[str, Any] | IdeaSpec | str | None = None,
) -> OrbitState:
    """Factory creating an initial OrbitState for the 7-agent linear pipeline."""
    from app.graph.budgets import BudgetManager

    if isinstance(idea, dict):
        parsed_idea = IdeaSpec(**idea)
    elif isinstance(idea, (IdeaSpec, str)):
        parsed_idea = idea
    else:
        parsed_idea = IdeaSpec()

    initial_run_id = run_id or f"orbit-run-{uuid4().hex[:12]}"
    initial_budgets = BudgetManager.initialize_budgets()

    return OrbitState(
        run_id=initial_run_id,
        tenant_id=tenant_id,
        user_id=user_id,
        idea=parsed_idea,
        status="pending",
        current_agent="problem_discovery",
        current_agent_index=1,
        feasibility_passed=True,
        budgets=initial_budgets,
        current_node="problem_discovery",
        feasibility={},
        design={},
        progress={},
        errors=[],
    )
