"use client";

import { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import {
    Database, Code2, Cpu, Server, Copy, Check, Terminal,
    Layers, Shield, ArrowRight, Zap, FileCode, CheckCircle2, Brain,
} from "lucide-react";
import { useStartupStore } from "@/lib/stores/startup-store";
import { CenterIntelligenceSection } from "@/components/cofounder/CenterIntelligenceSection";
import type { ExecutionPlan } from "@/types/api";

export function ArchitectureBuilder({
    projectId,
    projectName,
    plan,
}: {
    projectId?: string;
    projectName: string;
    plan: ExecutionPlan;
}) {
    const { name, techStack, dbTables, apiEndpoints } = useStartupStore();
    const [activeTab, setActiveTab] = useState<"intelligence" | "database" | "api" | "stack" | "setup">("intelligence");
    const [copied, setCopied] = useState<string | null>(null);

    const displayName = name || projectName;

    // Generate PostgreSQL DDL Schema based on project blueprint
    const dbSchemaSql = `-- Database Schema for ${projectName}
-- Generated by Orbit Idea Technical Architect Agent

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Users & Auth Table
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    email VARCHAR(255) UNIQUE NOT NULL,
    full_name VARCHAR(255),
    role VARCHAR(50) DEFAULT 'member' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Primary Business Entity
CREATE TABLE workspaces (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    owner_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE NOT NULL,
    status VARCHAR(50) DEFAULT 'active' NOT NULL,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Core Workflow Items
CREATE TABLE workflow_items (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    status VARCHAR(50) DEFAULT 'todo' NOT NULL,
    priority INT DEFAULT 1,
    payload JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_workspaces_owner ON workspaces(owner_id);
CREATE INDEX idx_workflow_workspace ON workflow_items(workspace_id);
`;

    // Generate OpenAPI Specification JSON
    const openApiSpec = JSON.stringify(
        {
            openapi: "3.0.3",
            info: {
                title: `${projectName} Core API`,
                version: "1.0.0",
                description: `REST API Specification generated by Technical Architect Agent`,
            },
            paths: {
                "/api/v1/workspaces": {
                    get: {
                        summary: "List user workspaces",
                        responses: { "200": { description: "Array of workspaces" } },
                    },
                    post: {
                        summary: "Create a new workspace",
                        requestBody: {
                            content: {
                                "application/json": {
                                    schema: {
                                        type: "object",
                                        required: ["name"],
                                        properties: { name: { type: "string" } },
                                    },
                                },
                            },
                        },
                        responses: { "201": { description: "Workspace created" } },
                    },
                },
                "/api/v1/workspaces/{id}/items": {
                    get: {
                        summary: "Fetch workflow items",
                        parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
                        responses: { "200": { description: "Workflow items" } },
                    },
                },
            },
        },
        null,
        2,
    );

    const setupCommands = `# ${projectName} Technical Setup Commands

# 1. Clone repository & install dependencies
git clone https://github.com/org/${projectName.toLowerCase().replaceAll(" ", "-")}.git
cd ${projectName.toLowerCase().replaceAll(" ", "-")}
npm install

# 2. Setup Database & Prisma ORM
npx prisma init
npx prisma migrate dev --name init

# 3. Start local Development Server
npm run dev
`;

    function copyText(text: string, id: string) {
        navigator.clipboard.writeText(text);
        setCopied(id);
        setTimeout(() => setCopied(null), 2000);
    }

    return (
        <div className="work-surface" style={{ padding: "32px", display: "flex", flexDirection: "column", gap: "28px" }}>
            {/* Header */}
            <div style={{ display: "flex", alignItems: "flex-start", justifyContent: "space-between", flexWrap: "wrap", gap: "20px" }}>
                <div>
                    <p className="section-kicker" style={{ display: "flex", alignItems: "center", gap: "6px" }}>
                        <Database className="size-4" style={{ color: "var(--indigo)" }} />
                        Technical Architect Engine
                    </p>
                    <h1 style={{ fontSize: "24px", fontWeight: 700, marginTop: "8px", color: "var(--text-primary)" }}>
                        System Architecture &amp; Code Blueprints
                    </h1>
                    <p style={{ fontSize: "14px", color: "var(--text-secondary)", marginTop: "4px", maxWidth: "600px" }}>
                        Production-ready database schemas, API specs, stack topology, and CLI commands for <strong>{projectName}</strong>.
                    </p>
                </div>

                {/* Tab Switcher */}
                <div style={{ display: "flex", background: "var(--surface-2)", padding: "4px", borderRadius: "var(--r-md)", border: "1px solid var(--border)" }}>
                    {[
                        { id: "intelligence", label: "Gemini Defense", icon: Brain },
                        { id: "database",     label: "PostgreSQL DDL", icon: Database },
                        { id: "api",          label: "OpenAPI Spec",   icon: Code2 },
                        { id: "stack",        label: "Tech Stack",     icon: Server },
                        { id: "setup",        label: "CLI Commands",   icon: Terminal },
                    ].map(({ id, label, icon: Icon }) => (
                        <button
                            key={id}
                            onClick={() => setActiveTab(id as any)}
                            style={{
                                display: "flex", alignItems: "center", gap: "8px",
                                padding: "8px 14px", borderRadius: "var(--r-sm)",
                                fontSize: "12px", fontWeight: 600,
                                color: activeTab === id ? "var(--text-primary)" : "var(--text-muted)",
                                background: activeTab === id ? "var(--surface-3)" : "transparent",
                                border: activeTab === id ? "1px solid var(--border-strong)" : "1px solid transparent",
                                transition: "all 120ms ease",
                            }}
                        >
                            <Icon className="size-3.5" />
                            {label}
                        </button>
                    ))}
                </div>
            </div>

            {/* Tab Contents */}
            <AnimatePresence mode="wait">
                {activeTab === "intelligence" && projectId && (
                    <motion.div key="intelligence" initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
                        <CenterIntelligenceSection
                            projectId={projectId}
                            workspace="architecture"
                            headlineOverride="Gemini Architecture Engine: Scalability & Token Cost Defense"
                        />
                    </motion.div>
                )}

                {activeTab === "database" && (
                    <motion.div key="database" initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
                        <div style={{ background: "var(--surface-2)", border: "1px solid var(--border)", borderRadius: "var(--r-lg)", overflow: "hidden" }}>
                            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", padding: "12px 20px", borderBottom: "1px solid var(--border)", background: "var(--surface-1)" }}>
                                <div style={{ display: "flex", alignItems: "center", gap: "8px", fontSize: "12px", color: "var(--text-secondary)", fontWeight: 600 }}>
                                    <FileCode className="size-4" style={{ color: "var(--indigo)" }} />
                                    schema.sql (PostgreSQL 16)
                                </div>
                                <button className="btn-secondary" style={{ height: "32px", fontSize: "12px" }} onClick={() => copyText(dbSchemaSql, "sql")}>
                                    {copied === "sql" ? <Check className="size-3.5" style={{ color: "var(--emerald)" }} /> : <Copy className="size-3.5" />}
                                    {copied === "sql" ? "Copied!" : "Copy SQL"}
                                </button>
                            </div>
                            <pre style={{ padding: "20px", fontSize: "12px", fontFamily: "monospace", color: "#A5B4FC", lineHeight: 1.6, overflowX: "auto", margin: 0, background: "#0D0D14" }}>
                                {dbSchemaSql}
                            </pre>
                        </div>
                    </motion.div>
                )}

                {activeTab === "api" && (
                    <motion.div key="api" initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
                        <div style={{ background: "var(--surface-2)", border: "1px solid var(--border)", borderRadius: "var(--r-lg)", overflow: "hidden" }}>
                            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", padding: "12px 20px", borderBottom: "1px solid var(--border)", background: "var(--surface-1)" }}>
                                <div style={{ display: "flex", alignItems: "center", gap: "8px", fontSize: "12px", color: "var(--text-secondary)", fontWeight: 600 }}>
                                    <Code2 className="size-4" style={{ color: "var(--cyan)" }} />
                                    openapi.json (v3.0.3)
                                </div>
                                <button className="btn-secondary" style={{ height: "32px", fontSize: "12px" }} onClick={() => copyText(openApiSpec, "json")}>
                                    {copied === "json" ? <Check className="size-3.5" style={{ color: "var(--emerald)" }} /> : <Copy className="size-3.5" />}
                                    {copied === "json" ? "Copied!" : "Copy JSON"}
                                </button>
                            </div>
                            <pre style={{ padding: "20px", fontSize: "12px", fontFamily: "monospace", color: "#6EE7B7", lineHeight: 1.6, overflowX: "auto", margin: 0, background: "#0D0D14" }}>
                                {openApiSpec}
                            </pre>
                        </div>
                    </motion.div>
                )}

                {activeTab === "stack" && (
                    <motion.div key="stack" initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
                        <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(240px, 1fr))", gap: "16px" }}>
                            {(techStack.length > 0 ? techStack : plan.technical_blueprint.stack).map((item) => (
                                <div key={item.layer} style={{ background: "var(--surface-2)", border: "1px solid var(--border)", borderRadius: "var(--r-md)", padding: "20px" }}>
                                    <span style={{ fontSize: "10px", fontWeight: 700, textTransform: "uppercase", color: "var(--indigo)", letterSpacing: "0.08em" }}>
                                        {item.layer}
                                    </span>
                                    <h4 style={{ fontSize: "16px", fontWeight: 700, color: "var(--text-primary)", marginTop: "4px" }}>
                                        {item.choice}
                                    </h4>
                                    <p style={{ fontSize: "12px", color: "var(--text-secondary)", marginTop: "8px", lineHeight: 1.5 }}>
                                        {item.reason}
                                    </p>
                                </div>
                            ))}
                        </div>
                    </motion.div>
                )}

                {activeTab === "setup" && (
                    <motion.div key="setup" initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
                        <div style={{ background: "var(--surface-2)", border: "1px solid var(--border)", borderRadius: "var(--r-lg)", overflow: "hidden" }}>
                            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", padding: "12px 20px", borderBottom: "1px solid var(--border)", background: "var(--surface-1)" }}>
                                <div style={{ display: "flex", alignItems: "center", gap: "8px", fontSize: "12px", color: "var(--text-secondary)", fontWeight: 600 }}>
                                    <Terminal className="size-4" style={{ color: "var(--purple)" }} />
                                    Terminal Setup Script
                                </div>
                                <button className="btn-secondary" style={{ height: "32px", fontSize: "12px" }} onClick={() => copyText(setupCommands, "sh")}>
                                    {copied === "sh" ? <Check className="size-3.5" style={{ color: "var(--emerald)" }} /> : <Copy className="size-3.5" />}
                                    {copied === "sh" ? "Copied!" : "Copy Commands"}
                                </button>
                            </div>
                            <pre style={{ padding: "20px", fontSize: "12px", fontFamily: "monospace", color: "#FCD34D", lineHeight: 1.6, overflowX: "auto", margin: 0, background: "#0D0D14" }}>
                                {setupCommands}
                            </pre>
                        </div>
                    </motion.div>
                )}
            </AnimatePresence>
        </div>
    );
}
